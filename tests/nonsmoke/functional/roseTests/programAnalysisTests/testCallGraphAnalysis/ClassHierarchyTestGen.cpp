/**
 * Generates random class hierarchies
 *
 * - first a random graph of arbitrary size is generated
 * - then loops are removed ( no loops allowed in a c++ class hierarchy)
 * - when the following situation occurs there is a compiler warning (ambiguity
 * of a): c0 -> c1 c2 c1 -> c2 i.e. for an edge (0->2) there exist a longer path
 * (0->1->2) so for every edge there is checked if such a path exist, if yes,
 * this edge is removed
 * - the resulting graph is printed out in topological order, therefore a map
 * exist, which maps classNr to fileNr ( because multiple classes can be printed
 * in one file)
 */

