#!/bin/bash
# Keep this count equal to MAX_OUTLINED_FUNC_PARAMETER_COUNT in libxomp.h.
MAX_PARAMETER_COUNT=256
echo "/* Generated by ./run_me_task_generator.sh; do not edit. */"

for ((count = 1; count <= MAX_PARAMETER_COUNT; ++count)); do
  echo "static void run_me_task_$count(void *data) {"
  echo "  typedef void (*FUNC_P)("
  for ((index = 1; index <= count; ++index)); do
    if ((index < count)); then
      echo "      void *,"
    else
      echo "      void *);"
    fi
  done
  echo "  FUNC_P func;"
  echo "  memcpy(&func, data, sizeof(func));"
  echo "  void *arguments[$count];"
  echo "  bool by_value[$count];"
  echo "  rex_unpack_fortran_task_arguments((const char *)data + sizeof(func),"
  echo "                                    $count, arguments, by_value);"
  echo "  func("
  for ((index = 0; index < count; ++index)); do
    if ((index + 1 < count)); then
      echo "      arguments[$index],"
    else
      echo "      arguments[$index]);"
    fi
  done
  echo "  rex_release_fortran_task_arguments($count, arguments, by_value);"
  echo "}"
done
